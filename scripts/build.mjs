// fill the ko text into a template (JS swaps languages; ko is also the no-JS fallback)
function fill(html, T) {
  html = html.replace(/(<(\w+)\b[^>]*?\sdata-t="(\w+)"[^>]*>)(<\/\2>)/g, (m, open, tag, k, close) => { if (!(k in T)) throw new Error('missing string ' + k); return open + esc(T[k]) + close; });
  html = html.replace(/<(img|span|a|button|select|div|section|nav)\b([^>]*?)\sdata-alt="(\w+)"([^>]*)>/g, (m, tag, a, k, b) => { if (!(k in T)) throw new Error('missing alt ' + k); return `<${tag}${a.replace(/\salt="[^"]*"/, '')} data-alt="${k}"${b.replace(/\salt="[^"]*"/, '')} alt="${esc(T[k])}">`; });
  html = html.replace(/<(\w+)\b([^>]*?)\sdata-(alt-label|aria)="(\w+)"([^>]*)>/g, (m, tag, a, attr, k, b) => { if (!(k in T)) throw new Error('missing label ' + k); return `<${tag}${a.replace(/\saria-label="[^"]*"/, '')} data-${attr}="${k}"${b.replace(/\saria-label="[^"]*"/, '')} aria-label="${esc(T[k])}">`; });
  return html.replace(/(<select id="lang"[^>]*>).*?(<\/select>)/s, (m, a, b) => a + opts + b);
}
